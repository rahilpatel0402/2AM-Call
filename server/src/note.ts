// Draft on-call note. Claude writes ONLY from the CallState (facts, unsaid items, flags, scores, feasibility).
// The physician chooses the disposition; the note records that choice and leaves the plan for the physician.
// Nothing is filed or signed automatically.
import type { CallState } from "./calls.js";
import { getResident } from "./db.js";
import { callClaude } from "./llm.js";
import { span } from "./tracing.js";

export type Disposition = "transfer" | "treat_in_place";

const DISPOSITION_TEXT: Record<Disposition, string> = {
  transfer: "Transfer to hospital",
  treat_in_place: "Treat in place at the facility",
};

const SYSTEM = `You draft an on-call physician note for a skilled nursing facility night call.

Rules:
- Use ONLY the information in the provided call data JSON. Do not add any fact, diagnosis, medication, value, or plan that is not in it.
- Every vital sign and fact must match the data exactly. If something is unknown, write "not reported".
- The physician has already chosen the disposition. Record it exactly as given. Do not argue for or against it.
- The rationale line restates, in one or two sentences, the facts from the data that the physician weighed (red flags, goals of care, facility capability tonight). It must not introduce new reasoning or recommendations.
- Leave "Plan:" followed by an empty line for the physician to write.
- Plain text. Use exactly these headings, in this order:
SITUATION
RELEVANT HISTORY SURFACED (not mentioned on the call)
ASSESSMENT DATA
RED FLAGS (rule based)
FACILITY CAPABILITY TONIGHT
PHYSICIAN DECISION
Plan:
- No em dashes or en dashes. Keep it under 250 words.`;

// Compact, source-of-truth view of the call for the model.
function callData(state: CallState, disposition: Disposition) {
  const r = getResident(state.residentId)!;
  return {
    resident: { name: r.name, age: r.age, sex: r.sex, room: r.room, code_status: r.code_status.value, molst: r.code_status.molst },
    call_time: new Date(state.clockStart).toLocaleString("en-US", { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" }),
    chief_concern: state.facts?.chief_concern?.text ?? null,
    onset: state.facts?.onset?.text ?? null,
    events: state.facts?.events.map(({ quote: _q, ...e }) => e) ?? [],
    symptoms_present: state.facts?.symptoms.filter((s) => s.present).map((s) => s.name) ?? [],
    symptoms_denied: state.facts?.symptoms.filter((s) => !s.present).map((s) => s.name) ?? [],
    vitals_tonight_vs_baseline: state.scores?.deltas.map((d) => `${d.label} ${d.current} (baseline ${d.baseline}, ${d.from === "call" ? "reported on call" : "last charted"})`) ?? [],
    news2: state.scores ? `${state.scores.news2.total} (${state.scores.news2.band})` : null,
    surfaced_not_mentioned: state.unsaid.map((u) => `${u.label}: ${u.value} [${u.source.label}]`),
    covered_on_call: state.covered.map((c) => c.label),
    red_flags: state.redFlags.map((f) => `${f.title}: ${f.why}`),
    goals_of_care_note: state.goalsNote,
    facility_tonight: state.feasibility.map((f) => `${f.available ? "Can" : "Cannot"}: ${f.capability} (${f.detail})`),
    prior_calls: state.priorCallsNote ?? `${state.priorCalls.length} prior night call(s) on record`,
    physician_decision: DISPOSITION_TEXT[disposition],
  };
}

export async function draftNote(state: CallState, disposition: Disposition): Promise<string> {
  const data = callData(state, disposition);
  return span("note.draft", "CHAIN", { "call.id": state.callId, "disposition": disposition, "input.value": JSON.stringify(data) }, async () => {
    const res = await callClaude({
      system: SYSTEM,
      messages: [{ role: "user", content: `Call data:\n${JSON.stringify(data, null, 2)}` }],
      maxTokens: 2000,
      effort: "low",
    });
    const text = res.text.replace(/[–—]/g, ", ").trim();
    return `${text}\n\nDraft generated by AI from the call record. Reviewed and signed by: ________`;
  }, (note) => ({ "output.value": note }));
}

// One-paragraph memory of the signed call, written to SurrealDB Agent Memory for the next on-call physician.
export function memorySummary(state: CallState, disposition: Disposition, physician: string, note: string): { reason: string; disposition: string; summary: string } {
  const flags = state.redFlags.map((f) => f.title).join(", ") || "none";
  const plan = note.split(/\n/).find((l, i, all) => /^plan:/i.test(all[i - 1] ?? "") || /^plan:\s*\S/i.test(l))?.replace(/^plan:\s*/i, "").trim();
  return {
    reason: state.facts?.chief_concern?.text ?? "night call",
    disposition: DISPOSITION_TEXT[disposition],
    summary: `Red flags at the time: ${flags}.${state.goalsNote ? ` ${state.goalsNote.split(". Red flags")[0]}.` : ""}${plan ? ` Plan: ${plan}` : ""} Signed by ${physician}.`,
  };
}
